/**
 * Deterministic routing pattern for natural-language model-identity questions, e.g.
 * "what model are you running on this channel?", "which model are you running right now",
 * "what model are you using?", "which model is this channel using". Anchored at both ends so
 * ordinary sentences that merely mention a model (or the plural "models", which belongs to
 * live-model-catalog-question) do not match.
 *
 * The app-mention route for these phrasings is catalog-driven (RegexAliases on show-channel-model
 * in command-catalog.json). This export is used only by the thread-reply intercept in
 * chat-module.js, which operates outside the catalog alias mechanism.
 */
const ModelIdentityPattern =
  /^(?:what|which)\s+(?:ai\s+|chat\s+|llm\s+)?model\s+(?:are\s+you(?:\s+(?:running|using|on))?|is\s+(?:this|the)\s+channel\s+(?:running|using|on)|is\s+(?:running|active|in\s+use))(?:\s+(?:on|in|for)\s+this\s+channel)?(?:\s+right\s+now|\s+now|\s+currently|\s+today)?\s*\?*$/i;

/**
 * Handle the `show-channel-model` command — reports the channel's model override (if any) and
 * the effective model, framed as a verified answer read from runtime configuration so users can
 * trust it is not an AI-generated guess.
 *
 * @param {import('../slack-app')} ArgSlackApp Slack app instance.
 * @param {import('../slack-app').AppMentionEventInfo} ArgEventInfo Event information.
 * @param {(ArgChannelID: string) => { lines: string[] }} ArgBuildChannelModelStatus Helper that
 *   formats the per-channel status block. Provided by chat-module.js so this handler stays
 *   independent of ChatModule's private helpers.
 * @returns {Promise<void>}
 */
async function HandleShowChannelModelCommandAsync(
  ArgSlackApp,
  ArgEventInfo,
  ArgBuildChannelModelStatus
) {
  const ChannelModelStatus = ArgBuildChannelModelStatus(ArgEventInfo.channel);
  const Lines = [
    `*Channel Model* — <#${ArgEventInfo.channel}>`,
    ...ChannelModelStatus.lines,
    '',
    ':white_check_mark: _Verified answer — read directly from runtime configuration (channel-override store + workspace settings), not generated by the AI model._',
  ];
  await ArgSlackApp.PostMessageTextAsync(ArgEventInfo.channel, ArgEventInfo.ts, Lines.join('\n'));
}

module.exports = HandleShowChannelModelCommandAsync;
module.exports.ModelIdentityPattern = ModelIdentityPattern;
